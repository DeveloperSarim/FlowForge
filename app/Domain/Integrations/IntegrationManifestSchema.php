<?php

namespace App\Domain\Integrations;

use Illuminate\Support\Arr;
use Illuminate\Support\Str;

/**
 * The contract every integration manifest (resources/integrations/**) must satisfy.
 *
 * {
 *   key, name, icon?, category, description?, base_url?, headers?, website?, docs_url?, popular?,
 *   auth: {type, ...} | [{type, ...}],          // none|api_key|bearer|basic|oauth2|oauth2_client_credentials|google_service_account|smtp|mysql
 *         oauth2 extras: scopes, authorize_params, client_auth (body|basic), token_type, token_query, refresh_url, pkce
 *         profile?: {endpoint, store: {field: "template over the response"}}   // who is connected, saved on the credential
 *   error_hints?: {"403": "what to check"}                                       // appended to HTTP errors (also per action)
 *   actions: [{key, name, description?, method, endpoint, query?, headers?, body?, body_format? (json|form),
 *              output_path?, output_fields?, output? (closed list of returned keys, built-ins), error_path?, timeout?,
 *              handler?, outputs?, inputs: [Input]}],
 *   triggers: [{key, name, type (webhook|polling|schedule|manual), inputs?, data_path?,       // webhook
 *               method?, endpoint?, query?, headers?, items_path?, id_field?}]                 // polling
 * }
 * Input = {key, label?, type, required?, default?, placeholder?, help?, options? [{value,label}],
 *          fallback? ("credentials.<profile field>" used when empty), escape? ("little_text")}
 *
 * Every HTTP integration (one with a base_url) also gets a generated "Make an API call" action that
 * reuses its credential against any path on that base URL.
 */
class IntegrationManifestSchema
{
    public const AUTH_TYPES = ['none', 'api_key', 'bearer', 'basic', 'oauth2', 'oauth2_client_credentials', 'google_service_account', 'smtp', 'mysql'];

    public const INPUT_TYPES = ['string', 'text', 'password', 'number', 'boolean', 'select', 'json', 'code', 'list', 'keyvalue', 'conditions', 'cron'];

    public const TRIGGER_TYPES = ['webhook', 'polling', 'schedule', 'manual', 'error'];

    public function normalize(array $manifest): array
    {
        $auth = $manifest['auth'] ?? ['type' => 'none'];
        $manifest['auth'] = Arr::isAssoc($auth) ? [$auth] : array_values($auth);
        $manifest['category'] ??= 'Other';
        $manifest['description'] ??= '';
        // Logos live in public/integrations/icons/{key}.svg (generated by scripts/build-integration-icons.mjs).
        $key = (string) ($manifest['key'] ?? '');
        $manifest['icon'] ??= collect(["{$key}.svg", "{$key}.mono.svg", "{$key}.site.svg", "{$key}.png"])
            ->map(fn ($file) => "/integrations/icons/{$file}")
            ->first(fn ($path) => $key !== '' && is_file(public_path($path)), 'plug');

        if (! empty($manifest['base_url']) && ! collect($manifest['actions'] ?? [])->contains('key', 'api_call')) {
            $manifest['actions'][] = self::apiCallAction($manifest['name'] ?? $key);
        }

        foreach (['actions', 'triggers'] as $kind) {
            $manifest[$kind] = array_values(array_map(function (array $operation) use ($kind) {
                $isHttp = $kind === 'actions' ? empty($operation['handler']) : ($operation['type'] ?? null) === 'polling';
                if ($isHttp) {
                    $method = $operation['method'] ?? 'GET';
                    // Uppercase literal verbs only; a {{ inputs.method }} template must keep its case.
                    $operation['method'] = str_contains($method, '{{') ? $method : strtoupper($method);
                }
                $operation['description'] ??= '';
                $operation['inputs'] = array_values(array_map(fn (array $input) => $input + [
                    'type' => 'string',
                    'required' => false,
                    'label' => Str::headline($input['key'] ?? ''),
                ], $operation['inputs'] ?? []));

                return $operation;
            }, $manifest[$kind] ?? []));
        }

        return $manifest;
    }

    /** Generic request against the integration's base URL, authenticated with its credential. */
    public static function apiCallAction(string $name): array
    {
        return [
            'key' => 'api_call',
            'name' => 'Make an API call',
            'description' => "Call any {$name} endpoint not covered by the actions above, using this app's credential.",
            'method' => '{{ inputs.method }}',
            'endpoint' => '{{ inputs.path }}',
            'restrict_to_base_url' => true,
            'query' => '{{ inputs.query }}',
            'headers' => '{{ inputs.headers }}',
            'body' => '{{ inputs.body }}',
            'inputs' => [
                ['key' => 'method', 'label' => 'Method', 'type' => 'select', 'required' => true, 'default' => 'GET', 'options' => array_map(
                    fn ($m) => ['value' => $m, 'label' => $m], ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'],
                )],
                ['key' => 'path', 'label' => 'Path', 'type' => 'string', 'required' => true, 'placeholder' => '/v1/resource', 'help' => 'Relative to the app\'s API base URL.'],
                ['key' => 'query', 'label' => 'Query parameters', 'type' => 'keyvalue', 'required' => false],
                ['key' => 'headers', 'label' => 'Headers', 'type' => 'keyvalue', 'required' => false],
                ['key' => 'body', 'label' => 'Body (JSON)', 'type' => 'json', 'required' => false],
            ],
        ];
    }

    /**
     * Hand-rolled (Laravel's wildcard validator costs ~20 ms per manifest; this is ~0.05 ms).
     *
     * @return list<string> validation errors (empty when valid)
     */
    public function validate(array $manifest): array
    {
        $e = [];
        $str = fn ($v) => is_string($v) && $v !== '';
        $template = '/^\{\{.+\}\}$/';

        if (! $str($manifest['key'] ?? null) || strlen($manifest['key']) > 100 || ! preg_match('/^[a-z0-9][a-z0-9_\-.]*$/', $manifest['key'])) {
            $e[] = 'The key field format is invalid.';
        }
        if (! $str($manifest['name'] ?? null) || mb_strlen($manifest['name']) > 120) {
            $e[] = 'The name field is required (max 120 characters).';
        }
        if (! $str($manifest['category'] ?? null) || mb_strlen($manifest['category']) > 60) {
            $e[] = 'The category field is required (max 60 characters).';
        }
        foreach (['icon', 'base_url', 'brand'] as $field) {
            if (isset($manifest[$field]) && ! is_string($manifest[$field])) {
                $e[] = "The {$field} field must be a string.";
            }
        }
        foreach (['website', 'docs_url'] as $field) {
            if (isset($manifest[$field]) && ! filter_var($manifest[$field], FILTER_VALIDATE_URL)) {
                $e[] = "The {$field} field must be a valid URL.";
            }
        }
        if (isset($manifest['headers']) && ! is_array($manifest['headers'])) {
            $e[] = 'The headers field must be an object.';
        }
        if (isset($manifest['popular']) && ! is_bool($manifest['popular'])) {
            $e[] = 'The popular field must be true or false.';
        }

        if (! is_array($manifest['auth'] ?? null) || $manifest['auth'] === []) {
            $e[] = 'The auth field is required.';
        }
        foreach ((array) ($manifest['auth'] ?? []) as $i => $auth) {
            $type = $auth['type'] ?? null;
            if (! in_array($type, self::AUTH_TYPES, true)) {
                $e[] = "auth.{$i}.type is invalid.";
            }
            if (isset($auth['in']) && ! in_array($auth['in'], ['header', 'query'], true)) {
                $e[] = "auth.{$i}.in must be header or query.";
            }
            if (isset($auth['in']) && ! $str($auth['name'] ?? null)) {
                $e[] = "auth.{$i}.name is required when \"in\" is set.";
            }
            if ($type === 'oauth2' || $type === 'oauth2_client_credentials') {
                foreach ($type === 'oauth2' ? ['authorize_url', 'token_url'] : ['token_url'] as $url) {
                    if (! $str($auth[$url] ?? null) || ! preg_match('#^(https://|\{\{)#', $auth[$url])) {
                        $e[] = "auth.{$i}.{$url} must be an https URL.";
                    }
                }
            }
            if (isset($auth['client_auth']) && ! in_array($auth['client_auth'], ['body', 'basic'], true)) {
                $e[] = "auth.{$i}.client_auth must be body or basic.";
            }
            foreach (['scopes', 'fields'] as $list) {
                if (isset($auth[$list]) && ! is_array($auth[$list])) {
                    $e[] = "auth.{$i}.{$list} must be an array.";
                }
            }
            foreach ((array) ($auth['fields'] ?? []) as $j => $field) {
                if (! $str($field['key'] ?? null)) {
                    $e[] = "auth.{$i}.fields.{$j}.key is required.";
                }
            }
        }

        foreach (['actions', 'triggers'] as $kind) {
            if (! is_array($manifest[$kind] ?? [])) {
                $e[] = "The {$kind} field must be an array.";

                continue;
            }
            $keys = [];
            foreach ($manifest[$kind] ?? [] as $i => $op) {
                $where = "{$kind}.{$i}";
                $key = $op['key'] ?? null;
                if (! $str($key) || ($kind === 'actions' && ! preg_match('/^[a-zA-Z0-9_\-.]+$/', $key))) {
                    $e[] = "{$where}.key is invalid.";
                } elseif (isset($keys[$key])) {
                    $e[] = "{$where}.key [{$key}] is duplicated.";
                }
                $keys[$key] = true;
                if (! $str($op['name'] ?? null)) {
                    $e[] = "{$where}.name is required.";
                }

                if ($kind === 'actions') {
                    $handler = $op['handler'] ?? null;
                    if ($handler !== null && ! array_key_exists($handler, WorkflowActionExecutor::HANDLERS)) {
                        $e[] = "{$where}.handler is invalid.";
                    }
                    if ($handler === null) {
                        if (! $str($op['method'] ?? null) || ! (in_array($op['method'], ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD'], true) || preg_match($template, $op['method']))) {
                            $e[] = "{$where}.method is invalid.";
                        }
                        if (! $str($op['endpoint'] ?? null)) {
                            $e[] = "{$where}.endpoint is required when handler is not present.";
                        }
                    }
                    if (isset($op['body_format']) && ! (in_array($op['body_format'], ['json', 'form'], true) || preg_match($template, $op['body_format']))) {
                        $e[] = "{$where}.body_format must be json or form.";
                    }
                    foreach (['outputs', 'output_fields', 'output'] as $arr) {
                        if (isset($op[$arr]) && ! is_array($op[$arr])) {
                            $e[] = "{$where}.{$arr} must be an array.";
                        }
                    }
                    if (isset($op['timeout']) && (! is_int($op['timeout']) || $op['timeout'] < 1 || $op['timeout'] > 900)) {
                        $e[] = "{$where}.timeout must be 1-900 seconds.";
                    }
                } else {
                    $type = $op['type'] ?? null;
                    if (! in_array($type, self::TRIGGER_TYPES, true)) {
                        $e[] = "{$where}.type is invalid.";
                    }
                    if ($type === 'polling' && ! $str($op['endpoint'] ?? null)) {
                        $e[] = "{$where}.endpoint is required for polling triggers.";
                    }
                }

                if (! is_array($op['inputs'] ?? [])) {
                    $e[] = "{$where}.inputs must be an array.";

                    continue;
                }
                foreach ($op['inputs'] ?? [] as $j => $input) {
                    if (! $str($input['key'] ?? null) || ! preg_match('/^[a-zA-Z0-9_\-]+$/', $input['key'])) {
                        $e[] = "{$where}.inputs.{$j}.key is invalid.";
                    }
                    if (! in_array($input['type'] ?? null, self::INPUT_TYPES, true)) {
                        $e[] = "{$where}.inputs.{$j}.type is invalid.";
                    }
                    if (($input['type'] ?? null) === 'select' && ! is_array($input['options'] ?? null)) {
                        $e[] = "{$where}.inputs.{$j}.options are required for select inputs.";
                    }
                }
            }
        }

        return $e;
    }
}
